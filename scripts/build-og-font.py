"""Subset the site's Inter font for the Cloudflare OG image renderer."""

import base64
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/fonts/inter-normal-core.woff2"
TARGET = ROOT / "src/lib/inter-og-font.ts"
TEXT = "IntDInteger Decomposition Calculator0123456789"

font = TTFont(SOURCE)
options = subset.Options()
options.layout_features = ["*"]  # Keep Inter's tabular-number feature.
options.name_IDs = ["*"]
options.name_languages = ["*"]
worker = subset.Subsetter(options=options)
worker.populate(text=TEXT)
worker.subset(font)

# Map digits to Inter's tnum alternates in this OG-only subset. This makes
# numeric shares tabular even in SVG rasterizers that ignore CSS font features.
feature = next(
    item.Feature
    for item in font["GSUB"].table.FeatureList.FeatureRecord
    if item.FeatureTag == "tnum"
)
mapping = font["GSUB"].table.LookupList.Lookup[feature.LookupListIndex[0]].SubTable[0].mapping
for table in font["cmap"].tables:
    if table.isUnicode():
        for codepoint in range(ord("0"), ord("9") + 1):
            table.cmap[codepoint] = mapping[table.cmap[codepoint]]
advances = {
    font["hmtx"].metrics[font.getBestCmap()[codepoint]][0]
    for codepoint in range(ord("0"), ord("9") + 1)
}
assert len(advances) == 1, "OG numerals must have equal advance widths"

sources = {}
for label, weight in (("REGULAR", 400), ("BOLD", 700)):
    static = instantiateVariableFont(
        font, {"wght": weight, "opsz": 32}, inplace=False, updateFontNames=True
    )
    del static["STAT"]
    static_cmap = static.getBestCmap()
    static_advances = {
        static["hmtx"].metrics[static_cmap[codepoint]][0]
        for codepoint in range(ord("0"), ord("9") + 1)
    }
    assert len(static_advances) == 1, f"{label} numerals must remain tabular"
    # resvg-wasm accepts these pinned instances as TTF. Its WOFF2 parser
    # rejects the same instances after fontTools recompresses them.
    static.flavor = None
    static.recalcTimestamp = False
    static["head"].modified = 3600000000
    buffer = BytesIO()
    static.save(buffer)
    sources[label] = buffer.getvalue()

TARGET.write_text(
    "// Generated by scripts/build-og-font.py from public/fonts/inter-normal-core.woff2.\n"
    + "".join(
        f'export const INTER_OG_{label}_TTF_BASE64 =\n  "{base64.b64encode(data).decode("ascii")}"\n'
        for label, data in sources.items()
    ),
    encoding="utf-8",
)
print(f"{TARGET.relative_to(ROOT)}: {sum(map(len, sources.values()))} bytes")
